#!/usr/bin/env node
// Regenerate src/license/scancode.ts from ScanCode LicenseDB, the second
// classification authority after the FSF list (#307). Run via
// `make license-table`. Takes an optional URL or local path to index.json.
// The fetch happens here, at maintenance time, never in the app.
import { readFileSync, writeFileSync } from "node:fs";
import { basename, join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

const SOURCE =
  process.argv[2] ?? "https://scancode-licensedb.aboutcode.org/index.json";
const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "src",
  "license",
  "scancode.ts",
);

// ScanCode category → blitsbom category. Unlisted categories (Unstated
// License, CLA, Other) are left out and stay unrecognized.
const CATEGORY = {
  "Public Domain": "public-domain",
  Permissive: "permissive",
  "Copyleft Limited": "copyleft",
  Copyleft: "strong-copyleft",
  // Licenses that restrict use or commercial redistribution.
  "Free Restricted": "proprietary",
  "Non-Commercial": "proprietary",
  "Proprietary Free": "proprietary",
  "Source-available": "proprietary",
  Commercial: "proprietary",
  "Patent License": "proprietary",
};

// ScanCode lists both as Permissive although their names state the
// category. Pinned until upstream fixes it.
const OVERRIDES = {
  "ESA-PL-strong-copyleft-2.4": "strong-copyleft",
  "ESA-PL-weak-copyleft-2.4": "copyleft",
};

// SPDX id syntax. Rejects ScanCode aliases with spaces ("GPL 2.0"), which
// would split into junk keys in the space-separated output.
const SPDX_ID = /^[A-Za-z0-9.+-]+$/;

/** SPDX License List ids, plus Fedora's registry refs that RPMs declare.
 * Other LicenseRef-* keys are ScanCode's own aliases, some of them
 * placeholders such as LicenseRef-LICENSE. */
function isWanted(id) {
  if (!id || !SPDX_ID.test(id)) return false;
  return !id.startsWith("LicenseRef-") || id.startsWith("LicenseRef-Fedora-");
}

const remote = /^https?:\/\//.test(SOURCE);
let raw;
if (remote) {
  const res = await fetch(SOURCE);
  if (!res.ok) throw new Error(`${SOURCE}: HTTP ${res.status}`);
  raw = await res.text();
} else {
  raw = readFileSync(SOURCE, "utf8");
}
const index = JSON.parse(raw);

const byId = new Map(); // lowercase id → [id, category]
for (const entry of index) {
  // WITH <exception> tails are stripped before lookup.
  if (entry.is_exception) continue;
  const ids = [
    entry.spdx_license_key,
    ...(entry.other_spdx_license_keys ?? []),
  ];
  for (const id of ids.filter(isWanted)) {
    const category = OVERRIDES[id] ?? CATEGORY[entry.category];
    if (!category) continue;
    const key = id.toLowerCase();
    const seen = byId.get(key);
    if (!seen) byId.set(key, [id, category]);
    else if (seen[1] !== category) {
      console.warn(
        `license-table: ${id} is ${seen[1]} and ${category}; keeping ${seen[1]}`,
      );
    }
  }
}

const groups = {};
for (const [id, category] of byId.values()) (groups[category] ??= []).push(id);

const date = new Date().toISOString().slice(0, 10);
const lines = [
  "/*",
  " * Copyright 2026 Ronny Trommer <ronny@no42.org>",
  " * SPDX-License-Identifier: MIT",
  " */",
  "",
  "// GENERATED by scripts/scancode-categories.mjs. Do not edit; run",
  "// `make license-table` instead.",
  `// Source: ${remote ? SOURCE : `local file ${basename(SOURCE)}`} (${date})`,
  "//",
  "// SPDX license ids by category, per ScanCode LicenseDB. classify.ts consults",
  "// this only for ids its FSF-based table does not hold. Space-separated",
  "// strings compress better than an object with one key per id.",
  "",
  "import type { LicenseCategory } from '../types';",
  "",
  "export const SCANCODE_IDS: Partial<Record<LicenseCategory, string>> = {",
];
for (const category of Object.keys(groups).sort()) {
  const ids = groups[category].sort((a, b) =>
    a.toLowerCase().localeCompare(b.toLowerCase()),
  );
  lines.push(`  '${category}':`, `    '${ids.join(" ")}',`);
}
lines.push("};", "");
const config = (await prettier.resolveConfig(OUT)) ?? {};
writeFileSync(
  OUT,
  await prettier.format(lines.join("\n"), { ...config, filepath: OUT }),
);
console.log(`license-table: ${byId.size} ids → ${OUT}`);
